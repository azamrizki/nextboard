// Claude Code is told at every launch, whichever login it uses and with live status off; the
// setting takes it back.
func TestClaudeIsToldNotToSign(t *testing.T) {
	var claude Agent
	for _, a := range Builtins() {
		if a.ID == "claude" {
			claude = a
		}
	}
	for _, live := range []bool{true, false} {
		p, err := Build(claude, Options{Mode: ModeFresh, LiveStatus: live})
		if err != nil {
			t.Fatal(err)
		}
		var hooks, wrap string
		for _, kv := range p.Env {
			if v, ok := strings.CutPrefix(kv, "NB_HOOKS="); ok {
				hooks = v
			}
			if v, ok := strings.CutPrefix(kv, "NB_WRAP="); ok {
				wrap = v
			}
		}
		if !strings.Contains(hooks, `"attribution":{"commit":"","pr":""}`) || !strings.Contains(hooks, `"includeCoAuthoredBy":false`) {
			t.Fatalf("live %v: %q", live, hooks)
		}
		if !strings.Contains(wrap, "--settings") {
			t.Fatalf("live %v: not passed: %q", live, wrap)
		}
	}
	p, err := Build(claude, Options{Mode: ModeFresh, LiveStatus: true, CoAuthor: true})
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(strings.Join(p.Env, " "), "attribution") {
		t.Fatalf("still told: %v", p.Env)
	}
}

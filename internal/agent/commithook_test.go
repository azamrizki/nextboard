// gitEnv is a git that reads no configuration but what a test gives it, and uses the hooks.
func gitEnv(t *testing.T, hooks string) []string {
	t.Helper()
	home := t.TempDir()
	env := append(os.Environ(), "HOME="+home, "GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_NOSYSTEM=1", "GIT_AUTHOR_NAME=Budi", "GIT_AUTHOR_EMAIL=budi@acme.id",
		"GIT_COMMITTER_NAME=Budi", "GIT_COMMITTER_EMAIL=budi@acme.id")
	return append(env, "GIT_CONFIG_COUNT=1", "GIT_CONFIG_KEY_0=core.hooksPath", "GIT_CONFIG_VALUE_0="+hooks)
}

type repo struct {
	t   *testing.T
	dir string
	env []string
}

// git is bounded, with everything it started: a hook that hangs must not stay behind on a
// shared host.
func (r repo) git(args ...string) (string, error) {
	r.t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "git", args...)
	cmd.Dir, cmd.Env = r.dir, r.env
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	cmd.Cancel = func() error { return syscall.Kill(-cmd.Process.Pid, syscall.SIGKILL) }
	cmd.WaitDelay = time.Second
	out, err := cmd.CombinedOutput()
	if ctx.Err() != nil {
		r.t.Fatalf("git %v hung\n%s", args, out)
	}
	return string(out), err
}

func (r repo) must(args ...string) string {
	r.t.Helper()
	out, err := r.git(args...)
	if err != nil {
		r.t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return out
}

func (r repo) hook(dir, name, body string) {
	r.t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		r.t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, name), []byte("#!/bin/sh\n"+body+"\n"), 0o755); err != nil {
		r.t.Fatal(err)
	}
}

func newRepo(t *testing.T) repo {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	hooks := filepath.Join(t.TempDir(), "git hooks") // a space on purpose
	if err := WriteCommitHooks(hooks); err != nil {
		t.Fatal(err)
	}
	r := repo{t: t, dir: t.TempDir(), env: gitEnv(t, hooks)}
	r.must("init", "-q", "-b", "main", ".")
	return r
}

func (r repo) commit(msg string) string {
	r.t.Helper()
	r.must("commit", "-q", "--allow-empty", "-m", msg)
	return r.must("log", "-1", "--format=%B")
}

// What agents write goes; what people write stays.
func TestCommitLosesAgentLinesOnly(t *testing.T) {
	r := newRepo(t)
	gone := []string{
		"Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
		"Co-authored-by: Claude Sonnet 4.5 (1M context) <noreply@anthropic.com>",
		"Co-authored-by: Codex <noreply@openai.com>",
		"co-authored-by: codex <noreply@openai.com>",
		"Co-authored-by: Cursor <cursoragent@cursor.com>",
		"Co-authored-by: aider (gpt-5) <aider@aider.chat>",
		"Co-authored-by: Copilot <198982749+Copilot@users.noreply.github.com>",
		"Co-authored-by: GitHub Copilot <copilot@users.noreply.github.com>",
		"Co-authored-by: Amp <amp@ampcode.com>",
		"Co-authored-by: Gemini <noreply@google.com>",
		"Co-authored-by: gemini-code-assist[bot] <176961590+gemini-code-assist[bot]@users.noreply.github.com>",
		"Co-authored-by: opencode <noreply@opencode.ai>",
		"Co-authored-by: Factory Droid <droid@factory.ai>",
		"🤖 Generated with [Claude Code](https://claude.com/claude-code)",
		"Generated with [Codex](https://openai.com/codex/).",
		"Generated by Copilot",
	}
	stay := []string{
		"Co-authored-by: Budi Santoso <budi@acme.id>",
		"Co-authored-by: Claude Dupont <claude.dupont@acme.com>",
		"Co-authored-by: Amparo Cruz <amparo@acme.com>",
		"Co-authored-by: Pi Patel <pi@acme.com>",
		"Signed-off-by: Budi <budi@acme.id>",
		"Generated with care by the team",
		"Claude and Codex were compared in this change.",
	}
	got := r.commit("fix: the subject\n\nWhy it changed.\n\n" + strings.Join(gone, "\n") + "\n" + strings.Join(stay, "\n"))
	for _, l := range gone {
		if strings.Contains(got, l) {
			t.Errorf("still there: %s", l)
		}
	}
	for _, l := range append(stay, "fix: the subject", "Why it changed.") {
		if !strings.Contains(got, l) {
			t.Errorf("lost: %s\n%s", l, got)
		}
	}
	// nothing left behind but the message
	if got := r.commit("only a subject\n\nCo-authored-by: Codex <noreply@openai.com>"); strings.TrimSpace(got) != "only a subject" {
		t.Fatalf("%q", got)
	}
	if out, _ := r.git("status", "--porcelain"); out != "" {
		t.Fatalf("left in the work tree: %s", out)
	}
	if ents, _ := filepath.Glob(filepath.Join(r.dir, ".git", "*.nextboard")); len(ents) != 0 {
		t.Fatalf("left in .git: %v", ents)
	}
	r.must("commit", "-q", "--amend", "--allow-empty", "-m", "amended\n\nCo-authored-by: Codex <noreply@openai.com>")
	if got := r.must("log", "-1", "--format=%B"); strings.Contains(got, "Codex") {
		t.Fatalf("amend: %q", got)
	}
}

// The repository's own hooks run as if nothing stood between, and can still say no.
func TestRepositoryHooksStillRun(t *testing.T) {
	r := newRepo(t)
	own := filepath.Join(r.dir, ".git", "hooks")
	trace := filepath.Join(t.TempDir(), "trace")
	r.hook(own, "pre-commit", "echo pre-commit >>'"+trace+"'")
	r.hook(own, "commit-msg", "echo commit-msg:$(grep -c 'Co-authored-by: Codex' \"$1\") >>'"+trace+"'; echo 'Change-Id: I123' >>\"$1\"")
	r.hook(own, "post-commit", "echo post-commit >>'"+trace+"'")
	got := r.commit("subject\n\nCo-authored-by: Codex <noreply@openai.com>")
	if !strings.Contains(got, "Change-Id: I123") || strings.Contains(got, "Codex") {
		t.Fatalf("message %q", got)
	}
	b, _ := os.ReadFile(trace)
	if s := string(b); s != "pre-commit\ncommit-msg:1\npost-commit\n" {
		t.Fatalf("hooks ran as %q", s)
	}
	// and a hook that says no still stops the commit
	r.hook(own, "pre-commit", "echo nope >&2; exit 3")
	if out, err := r.git("commit", "--allow-empty", "-m", "blocked"); err == nil || !strings.Contains(out, "nope") {
		t.Fatalf("pre-commit: %v %s", err, out)
	}
	r.hook(own, "pre-commit", "exit 0")
	r.hook(own, "commit-msg", "exit 1")
	if _, err := r.git("commit", "--allow-empty", "-m", "blocked"); err == nil {
		t.Fatal("commit-msg could not stop the commit")
	}
}

// A repository with its own hooks folder (husky), and one that names ours.
func TestRepositoryHooksPath(t *testing.T) {
	r := newRepo(t)
	trace := filepath.Join(t.TempDir(), "trace")
	r.hook(filepath.Join(r.dir, ".husky"), "pre-commit", "echo husky >>'"+trace+"'")
	r.must("config", "core.hooksPath", ".husky")
	if got := r.commit("subject\n\nCo-authored-by: Codex <noreply@openai.com>"); strings.Contains(got, "Codex") {
		t.Fatalf("message %q", got)
	}
	if b, _ := os.ReadFile(trace); string(b) != "husky\n" {
		t.Fatalf("husky ran as %q", b)
	}
	// an agent that writes the value it sees must not make the hook call itself
	var hooks string
	for _, kv := range r.env {
		if v, ok := strings.CutPrefix(kv, "GIT_CONFIG_VALUE_0="); ok {
			hooks = v
		}
	}
	r.must("config", "core.hooksPath", hooks)
	if got := r.commit("again\n\nCo-authored-by: Codex <noreply@openai.com>"); strings.Contains(got, "Codex") {
		t.Fatalf("message %q", got)
	}
	// nor when it is the same folder under another name
	alias := filepath.Join(t.TempDir(), "alias")
	if err := os.Symlink(hooks, alias); err != nil {
		t.Fatal(err)
	}
	r.must("config", "core.hooksPath", alias)
	if got := r.commit("once more\n\nCo-authored-by: Codex <noreply@openai.com>"); strings.Contains(got, "Codex") {
		t.Fatalf("message %q", got)
	}
}

// Hooks that read standard input still get it, and a push to a local bare repository can be refused.
func TestPushHooksPassThrough(t *testing.T) {
	r := newRepo(t)
	bare := repo{t: t, dir: t.TempDir(), env: r.env}
	bare.must("init", "-q", "--bare", ".")
	r.must("remote", "add", "origin", bare.dir)
	r.commit("one")
	seen := filepath.Join(t.TempDir(), "seen")
	r.hook(filepath.Join(r.dir, ".git", "hooks"), "pre-push", "cat >'"+seen+"'; echo \"$1\" >>'"+seen+"'")
	r.must("push", "-q", "origin", "main")
	b, _ := os.ReadFile(seen)
	if !strings.Contains(string(b), "refs/heads/main") || !strings.Contains(string(b), "origin") {
		t.Fatalf("pre-push saw %q", b)
	}
	bare.hook(filepath.Join(bare.dir, "hooks"), "pre-receive", "echo refused >&2; exit 1")
	r.commit("two")
	if out, err := r.git("push", "-q", "origin", "main"); err == nil || !strings.Contains(out, "refused") {
		t.Fatalf("pre-receive: %v %s", err, out)
	}
}

// git in a worktree finds the hooks of the repository it belongs to.
func TestWorktreeUsesTheRepositoryHooks(t *testing.T) {
	r := newRepo(t)
	r.commit("one")
	trace := filepath.Join(t.TempDir(), "trace")
	r.hook(filepath.Join(r.dir, ".git", "hooks"), "pre-commit", "echo ran >>'"+trace+"'")
	wt := filepath.Join(t.TempDir(), "wt")
	r.must("worktree", "add", "-q", "-b", "side", wt)
	w := repo{t: t, dir: wt, env: r.env}
	if got := w.commit("two\n\nCo-authored-by: Codex <noreply@openai.com>"); strings.Contains(got, "Codex") {
		t.Fatalf("message %q", got)
	}
	if b, _ := os.ReadFile(trace); string(b) != "ran\n" {
		t.Fatalf("hook ran as %q", b)
	}
}

func TestWriteCommitHooksAgain(t *testing.T) {
	dir := t.TempDir()
	for range 2 {
		if err := WriteCommitHooks(dir); err != nil {
			t.Fatal(err)
		}
	}
	info, err := os.Stat(filepath.Join(dir, "commit-msg"))
	if err != nil || info.Mode().Perm()&0o100 == 0 {
		t.Fatalf("%v %v", info, err)
	}
	if _, err := os.Lstat(filepath.Join(dir, "push-to-checkout")); !os.IsNotExist(err) {
		t.Fatal("push-to-checkout changes what git does just by being there")
	}
}


package tools

import "testing"

func TestReadOnlyCommand(t *testing.T) {
	cases := []struct {
		cmd  string
		want bool
	}{
		// simple reads
		{"ls", true},
		{"ls -la /tmp", true},
		{"  pwd  ", true},
		{"cat README.md", true},
		{"head -n 20 main.go", true},
		{"tail -f log.txt", true},
		{"wc -l *.go", true},
		{"file main.go", true},
		{"stat -c %s go.mod", true},
		{"du -sh .", true},
		{"df -h", true},
		{"which go", true},
		{"type ls", true},
		{"echo hello world", true},
		{"printf '%s\\n' a b", true},
		{"date +%Y-%m-%d", true},
		{"uname -a", true},
		{"whoami", true},
		{"id -u", true},
		{"tree -L 2", true},
		{"realpath ../x", true},
		{"basename /a/b.go .go", true},
		{"dirname /a/b.go", true},
		{"cd web", true},
		{"true", true},

		// search and text tools
		{"grep -rn 'TODO' .", true},
		{"grep -r foo *", true},
		{"grep 'foo$' file", true},
		{"rg -n --hidden 'func main' -g '*.go'", true},
		{"rg -e -x", true},
		{"ag foo", true},
		{"sort -u names.txt", true},
		{"sort -t, -k2 data.csv", true},
		{"uniq -c", true},
		{"uniq names.txt", true},
		{"cut -d: -f1 /etc/passwd", true},
		{"tr a-z A-Z", true},
		{"diff a.txt b.txt", true},
		{"cmp a b", true},
		{"jq '.name' package.json", true},
		{"column -t", true},
		{"nl main.go", true},
		{"find . -name '*.go' -type f", true},
		{`find . -name "*.ts" -not -path './node_modules/*'`, true},
		{`find . \( -name a -o -name b \) -print`, true},

		// pipes, lists and harmless redirections
		{"ls -la | head -5", true},
		{"cat a | grep x | sort | uniq -c | sort -rn | head", true},
		{"git status && git diff --stat", true},
		{"ls missing || echo none", true},
		{"pwd; ls", true},
		{"ls 2>&1 | grep x", true},
		{"ls >/dev/null", true},
		{"ls > /dev/null 2>&1", true},
		{"ls 2>/dev/null", true},
		{"ls 2> /dev/null", true},
		{"ls &>/dev/null", true},
		{"ls >>/dev/null", true},
		{"echo oops >&2", true},
		{"wc -l < main.go", true},
		{"cd web && npm ls --depth=0", true},
		{"echo 'a > b; c | d && e'", true},
		{`echo "a > b; c | d"`, true},
		{`echo a\;b`, true},
		{`"ls" -l`, true},

		// git
		{"git status", true},
		{"git status --porcelain", true},
		{"git diff HEAD~1 -- main.go", true},
		{"git log --oneline -n 20", true},
		{"git log --format='%H %s'", true},
		{"git show HEAD:go.mod", true},
		{"git rev-parse --show-toplevel", true},
		{"git ls-files", true},
		{"git ls-tree -r HEAD", true},
		{"git blame main.go", true},
		{"git describe --tags", true},
		{"git shortlog -sn", true},
		{"git grep -n foo", true},
		{"git branch", true},
		{"git branch -a", true},
		{"git branch -vv", true},
		{"git branch --show-current", true},
		{"git tag", true},
		{"git tag -l", true},
		{"git remote", true},
		{"git remote -v", true},
		{"git config --get user.name", true},
		{"git config --get-all remote.origin.url", true},
		{"git config --list", true},
		{"git config -l", true},
		{"git stash list", true},
		{"git -C /tmp/repo status", true},
		{"git --no-pager log -1", true},
		{"git diff --output-indicator-new=+", true},

		// go, node, npm, python
		{"go version", true},
		{"go env", true},
		{"go env GOPATH GOMODCACHE", true},
		{"go list ./...", true},
		{"go list -m all", true},
		{"node --version", true},
		{"npm --version", true},
		{"npm ls", true},
		{"npm list --all", true},
		{"npm view react version", true},
		{"python --version", true},
		{"python3 --version", true},

		// redirections that write
		{"echo hi > out.txt", false},
		{"echo hi >> out.txt", false},
		{"echo hi >out.txt", false},
		{"ls > /dev/nullx", false},
		{"ls 1>/tmp/x", false},
		{"ls &>out", false},
		{"ls >| out", false},
		{"ls >&out", false},
		{"cat <> file", false},
		{"cat <<EOF", false},
		{"cat <<< text", false},
		{`ls > "/dev/null"`, false},

		// substitutions and expansions
		{"echo $(rm -rf x)", false},
		{"echo `rm -rf x`", false},
		{"echo $HOME", false},
		{"echo ${HOME}", false},
		{`echo "$HOME"`, false},
		{`echo "\$HOME"`, false},
		{"echo $'\\x41'", false},
		{"cat <(ls)", false},
		{"diff <(ls a) <(ls b)", false},
		{"tee >(cat)", false},
		{"(ls)", false},
		{"ls; (rm x)", false},
		{"{ ls; }", false},

		// lists that hide a write
		{"ls; rm -rf /", false},
		{"ls && rm x", false},
		{"ls || rm x", false},
		{"ls | sh", false},
		{"ls | bash", false},
		{"cat x | python3", false},
		{"find . | xargs rm", false},
		{"echo hi | tee out", false},
		{"ls & rm x", false},
		{"ls &", false},
		{"ls |& grep x", false},
		{"ls\nrm x", false},
		{"ls\rrm x", false},
		{"ls # comment", false},
		{"ls &&", false},
		{"&& ls", false},
		{"ls ;; ls", false},
		{"ls | | grep", false},
		{"", false},
		{"   ", false},
		{"echo 'unclosed", false},
		{`echo "unclosed`, false},
		{`echo trailing\`, false},

		// programs not allowed
		{"rm x", false},
		{"FOO=1 ls", false},
		{"A=1", false},
		{"sudo ls", false},
		{"exec ls", false},
		{"eval ls", false},
		{"env", false},
		{"env ls", false},
		{"source x.sh", false},
		{". x.sh", false},
		{"xargs ls", false},
		{"tee out", false},
		{"less file", false},
		{"bash -c ls", false},
		{"sh -c 'ls'", false},
		{"/bin/ls", false},
		{"./ls", false},
		{"l*", false},
		{"make", false},
		{"curl https://example.com", false},
		{"sed -i s/a/b/ f", false},
		{"awk '{print}' f", false},
		{"chmod +x f", false},
		{"touch f", false},
		{"mkdir d", false},
		{"cp a b", false},
		{"mv a b", false},
		{"ln -s a b", false},
		{"kill 1", false},
		{"time ls", false},
		{"nohup ls", false},
		{"timeout 5 ls", false},
		{"command ls", false},
		{"! ls", false},

		// options that write or run something
		{"find . -delete", false},
		{"find . -name x -exec rm {} \\;", false},
		{"find . -execdir ls \\;", false},
		{"find . -ok rm {} \\;", false},
		{"find . -okdir rm {} \\;", false},
		{"find . -fprint out", false},
		{"find . -fprint0 out", false},
		{"find . -fprintf out %p", false},
		{"find . -fls out", false},
		{"find . -name *.go", false},
		{"find {.,-delete}", false},
		{"sort -o out in", false},
		{"sort -uo out in", false},
		{"sort --output=out in", false},
		{"sort --out=x in", false},
		{"sort --compress-program=sh in", false},
		{"sort *", false},
		{"uniq in out", false},
		{"uniq a{,b}", false},
		{"tree -o out", false},
		{"tree -R -H .", false},
		{"date -s now", false},
		{"date --set=now", false},
		{"file -C -m magic", false},
		{"rg --pre=sh foo", false},
		{"rg --pre sh foo", false},
		{"rg --pre-glob '*' foo", false},
		{"rg --hostname-bin=sh foo", false},
		{"rg foo *.go", false},
		{"ag --pager=sh foo", false},

		// git that writes or runs something
		{"git", false},
		{"git commit -m x", false},
		{"git push", false},
		{"git pull", false},
		{"git fetch", false},
		{"git checkout main", false},
		{"git reset --hard", false},
		{"git stash", false},
		{"git stash pop", false},
		{"git add .", false},
		{"git branch new", false},
		{"git branch -D old", false},
		{"git branch --list 'feat*'", false},
		{"git tag v1", false},
		{"git tag -d v1", false},
		{"git remote add o url", false},
		{"git remote -v show", false},
		{"git config user.name x", false},
		{"git config --get", false},
		{"git config --unset user.name", false},
		{"git config --list --global", false},
		{"git -c core.pager=sh log", false},
		{"git -c core.fsmonitor=x status", false},
		{"git --git-dir=/x status", false},
		{"git --work-tree=/x status", false},
		{"git -C", false},
		{"git diff --output=x", false},
		{"git log --output x", false},
		{"git log --out=x", false},
		{"git diff --ext-diff", false},
		{"git grep -O foo", false},
		{"git grep -Ovim foo", false},
		{"git grep --open-files-in-pager=sh foo", false},
		{"git log *", false},

		// go, node, npm, python that run something
		{"go build ./...", false},
		{"go test ./...", false},
		{"go run .", false},
		{"go mod tidy", false},
		{"go env -w GOFLAGS=x", false},
		{"go env -u GOFLAGS", false},
		{"go list -toolexec sh ./...", false},
		{"go list -exec=sh ./...", false},
		{"go list -mod=mod ./...", false},
		{"go list -export ./...", false},
		{"go", false},
		{"node", false},
		{"node -e 'x'", false},
		{"node --version x", false},
		{"node script.js", false},
		{"npm install", false},
		{"npm run build", false},
		{"npm ls --logs-dir=/x", false},
		{"npm --prefix x ls", false},
		{"npm", false},
		{"python -c 'print(1)'", false},
		{"python3 x.py", false},
		{"python3 -V", false},
	}
	for _, c := range cases {
		if got := ReadOnlyCommand(c.cmd); got != c.want {
			t.Errorf("ReadOnlyCommand(%q) = %v, want %v", c.cmd, got, c.want)
		}
	}
}
